"""Emit paper/numbers.tex so that every number in the paper comes from the runs."""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "results/runs"
PAPER = ROOT / "paper"

ORDER = [
    ("resnet18_frozen_noaug", "One"),
    ("resnet18_frozen_aug", "Two"),
    ("resnet18_last_stage_noaug", "Three"),
    ("resnet18_last_stage_aug", "Four"),
    ("mobilenet_v3_small_last_stage_aug", "Five"),
    ("resnet18_scratch_noaug", "Six"),
    ("resnet18_last_stage_aug_f101n", "Seven"),
    ("resnet18_last_stage_aug_f101n_nodedup", "Eight"),
    ("mobilenet_v3_small_f101n", "Nine"),
    ("mobilenet_v3_small_kd_f101n", "Ten"),
    ("mobilenet_v3_small_kd_f101n_a02", "Eleven"),
    ("resnet18_last_stage_aug_f101n_e24", "Twelve"),
    ("resnet18_last_stage_aug_seed7", "FourSeed"),
]


def pct(x: float) -> str:
    return f"{100.0 * x:.1f}"


def load(run: str) -> dict:
    base = RUNS / run
    with open(base / "results.json", encoding="utf-8") as fh:
        res = json.load(fh)
    with open(base / "history.csv", encoding="utf-8") as fh:
        hist = list(csv.DictReader(fh))
    res["train_time_min"] = sum(float(r["epoch_time_s"]) for r in hist) / 60.0
    res["epochs"] = len(hist)
    res["epoch_time_mean"] = sum(float(r["epoch_time_s"]) for r in hist) / len(hist)
    res["train_acc_last"] = float(hist[-1]["train_acc"])
    return res


def main() -> None:
    comp_path = ROOT / "results/tables/complexity.json"
    comp = {r["run"]: r for r in json.loads(comp_path.read_text(encoding="utf-8"))} if comp_path.exists() else {}
    lines = ["% AUTO-GENERATED by scripts/make_paper_numbers.py -- do not edit by hand.", ""]
    acc = {}
    for run, tag in ORDER:
        if not (RUNS / run / "results.json").exists():
            continue
        res = load(run)
        val, test, can = res["val"], res["test"], res["canteen"]
        acc[tag] = pct(test["accuracy"])
        lines += [
            f"\\newcommand{{\\accTest{tag}}}{{{pct(test['accuracy'])}}}",
            f"\\newcommand{{\\foneTest{tag}}}{{{pct(test['macro_f1'])}}}",
            f"\\newcommand{{\\accVal{tag}}}{{{pct(val['accuracy'])}}}",
            f"\\newcommand{{\\accCan{tag}}}{{{pct(can['accuracy'])}}}",
            f"\\newcommand{{\\foneCan{tag}}}{{{pct(can['macro_f1'])}}}",
            f"\\newcommand{{\\gap{tag}}}{{{100.0 * (test['accuracy'] - can['accuracy']):.1f}}}",
            f"\\newcommand{{\\eceTest{tag}}}{{{test['ece']:.3f}}}",
            f"\\newcommand{{\\eceCan{tag}}}{{{can['ece']:.3f}}}",
            f"\\newcommand{{\\trainTime{tag}}}{{{res['train_time_min']:.1f}}}",
            f"\\newcommand{{\\epochSec{tag}}}{{{res['epoch_time_mean']:.0f}}}",
            f"\\newcommand{{\\epochs{tag}}}{{{res['epochs']}}}",
            f"\\newcommand{{\\bestEpoch{tag}}}{{{res['best']['epoch']}}}",
            f"\\newcommand{{\\trainAcc{tag}}}{{{pct(res['train_acc_last'])}}}",
        ]
        if run in comp:
            c = comp[run]
            lines += [
                f"\\newcommand{{\\params{tag}}}{{{c['params_m']:.2f}}}",
                f"\\newcommand{{\\macs{tag}}}{{{c['macs_g']:.2f}}}",
                f"\\newcommand{{\\latGpu{tag}}}{{{c['gpu_latency_ms_mean']:.1f}}}",
                f"\\newcommand{{\\latCpu{tag}}}{{{c['cpu_latency_ms_mean']:.1f}}}",
                f"\\newcommand{{\\fpsGpu{tag}}}{{{c['gpu_fps']:.0f}}}",
            ]
    a = {k: float(v) for k, v in acc.items()}
    acan = {tag: 100.0 * load(run)["canteen"]["accuracy"] for run, tag in ORDER if tag in a}
    def delta(x: str, y: str) -> str:
        return f"{a[x] - a[y]:+.1f}"
    def delta_can(x: str, y: str) -> str:
        return f"{acan[x] - acan[y]:+.1f}"
    lines += [
        "",
        f"\\newcommand{{\\gainAugFrozen}}{{{delta('Two', 'One')}}}",
        f"\\newcommand{{\\gainAugFinetune}}{{{delta('Four', 'Three')}}}",
        f"\\newcommand{{\\gainFinetuneNoaug}}{{{delta('Three', 'One')}}}",
        f"\\newcommand{{\\gainFinetuneAug}}{{{delta('Four', 'Two')}}}",
        f"\\newcommand{{\\gainMobile}}{{{delta('Five', 'Four')}}}",
        f"\\newcommand{{\\gainCanFinetuneNoaug}}{{{delta_can('Three', 'One')}}}",
        f"\\newcommand{{\\gainCanFinetuneAug}}{{{delta_can('Four', 'Two')}}}",
        f"\\newcommand{{\\gainCanAugFrozen}}{{{delta_can('Two', 'One')}}}",
        f"\\newcommand{{\\gainCanAugFinetune}}{{{delta_can('Four', 'Three')}}}",
    ]
    if "Seven" in a and "Four" in a:
        lines += [
            f"\\newcommand{{\\gainExternal}}{{{delta('Seven', 'Four')}}}",
            f"\\newcommand{{\\gainCanExternal}}{{{delta_can('Seven', 'Four')}}}",
            f"\\newcommand{{\\gainTarget}}{{{a['Seven'] - a['Four']:.1f}}}",
        ]
    if "Eight" in a and "Seven" in a:
        lines += [
            f"\\newcommand{{\\leakTest}}{{{delta('Eight', 'Seven')}}}",
            f"\\newcommand{{\\leakCan}}{{{delta_can('Eight', 'Seven')}}}",
        ]
    if {"Nine", "Ten", "Eleven"} <= set(a):
        lines += [
            r"\newcommand{\gainDataMobile}{" + delta("Nine", "Five") + "}",
            r"\newcommand{\gainCanDataMobile}{" + delta_can("Nine", "Five") + "}",
            r"\newcommand{\kdOneTest}{" + delta("Ten", "Nine") + "}",
            r"\newcommand{\kdOneCan}{" + delta_can("Ten", "Nine") + "}",
            r"\newcommand{\kdTwoTest}{" + delta("Eleven", "Nine") + "}",
            r"\newcommand{\kdTwoCan}{" + delta_can("Eleven", "Nine") + "}",
            r"\newcommand{\kdOneVal}{" + format(a["Ten"] - a["Nine"], "+.1f") + "}",
            r"\newcommand{\kdTwoVal}{" + format(a["Eleven"] - a["Nine"], "+.1f") + "}",
            r"\newcommand{\gainMobileCost}{" + format(abs(a["Five"] - a["Four"]), ".1f") + "}",
        ]
    run_of = {tag: run for run, tag in ORDER}
    if run_of.get("Five") in comp and run_of.get("Four") in comp:
        c5, c4 = comp[run_of["Five"]], comp[run_of["Four"]]
        lines += [
            f"\\newcommand{{\\speedCpuFive}}{{{100.0 * (1 - c5['cpu_latency_ms_mean'] / c4['cpu_latency_ms_mean']):.0f}}}",
            f"\\newcommand{{\\slowGpuFive}}{{{100.0 * (c5['gpu_latency_ms_mean'] / c4['gpu_latency_ms_mean'] - 1):.0f}}}",
        ]
    if "Six" in a:
        lines += [
            f"\\newcommand{{\\gainScratch}}{{{delta('Six', 'Four')}}}",
            f"\\newcommand{{\\gainCanScratch}}{{{delta_can('Six', 'Four')}}}",
            f"\\newcommand{{\\scratchDrop}}{{{a['Four'] - a['Six']:.1f}}}",
            f"\\newcommand{{\\scratchDropCan}}{{{acan['Four'] - acan['Six']:.1f}}}",
        ]

    # --- post-hoc temperature scaling (scripts/fit_temperature.py) ---
    cal_path = ROOT / "results/tables/calibration.json"
    if cal_path.exists():
        cal = {r["run"]: r for r in json.loads(cal_path.read_text(encoding="utf-8"))}
        for run, tag in ORDER:
            if run not in cal:
                continue
            c = cal[run]
            lines += [
                f"\\newcommand{{\\temp{tag}}}{{{c['temperature']:.2f}}}",
                f"\\newcommand{{\\eceTestCal{tag}}}{{{c['test']['after']['ece']:.3f}}}",
                f"\\newcommand{{\\eceCanCal{tag}}}{{{c['canteen']['after']['ece']:.3f}}}",
            ]
    # --- test-time augmentation and proxy resampling (scripts/eval_tta.py) ---
    tta_path = ROOT / "results/tables/tta.json"
    if tta_path.exists():
        tta = json.loads(tta_path.read_text(encoding="utf-8"))
        run_of = {tag: run for run, tag in ORDER}
        split_macro = {"test": "Test", "canteen": "Can", "canteen_s7": "Resample"}
        for tag in ("Four", "Seven"):
            entry = tta.get(run_of.get(tag, ""))
            if not entry:
                continue
            for split, suffix in split_macro.items():
                views = entry["splits"].get(split, {})
                for view in ("hflip", "fivecrop", "scales"):
                    if view in views:
                        name = view.replace("crop", "").capitalize()
                        lines.append(
                            f"\\newcommand{{\\tta{name}{suffix}{tag}}}"
                            f"{{{pct(views[view]['accuracy'])}}}"
                        )
        four = tta.get(run_of.get("Four", ""), {}).get("splits", {}).get("canteen_s7", {})
        seven = tta.get(run_of.get("Seven", ""), {}).get("splits", {}).get("canteen_s7", {})
        if four and seven:
            lines += [
                f"\\newcommand{{\\redrawCanFour}}{{{pct(four['base']['accuracy'])}}}",
                f"\\newcommand{{\\redrawCanSeven}}{{{pct(seven['base']['accuracy'])}}}",
                f"\\newcommand{{\\redrawGapSeven}}"
                f"{{{100.0 * (seven['base']['accuracy'] - four['base']['accuracy']):.1f}}}",
            ]

    # --- Chinese canteen head (21-way) -------------------------------------
    # The canteen runs have no results.json: their metrics live in
    # results/tables/cn241_*.json, written by scripts/train_cn241.py.
    tab = ROOT / "results/tables"

    def tj(name: str) -> dict:
        return json.loads((tab / name).read_text(encoding="utf-8"))

    sc = tj("split_counts.json")
    pre = tj("cn241_all_pretrain.json")
    c21 = tj("cn241_21.json")
    dep = tj("cn241_21_pre.json")
    fus = tj("cn241_21_confusion.json")
    lines += [
        f"\\newcommand{{\\cnPreTest}}{{{pct(pre['test']['top1'])}}}",
        f"\\newcommand{{\\cnPreTopFive}}{{{pct(pre['test']['top5'])}}}",
        f"\\newcommand{{\\cnPreEce}}{{{100.0 * pre['test']['ece']:.1f}}}",
        f"\\newcommand{{\\cnPreVal}}{{{pct(pre['best_val_acc'])}}}",
        f"\\newcommand{{\\cnPreEpochs}}{{{len(pre['history'])}}}",
        f"\\newcommand{{\\cnPreTrainN}}{{{sc['cn241_all/train']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnPreTestN}}{{{pre['test']['n']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnNoPreTest}}{{{pct(c21['test']['top1'])}}}",
        f"\\newcommand{{\\cnNoPreVal}}{{{pct(c21['best_val_acc'])}}}",
        f"\\newcommand{{\\cnNoPreTopFive}}{{{pct(c21['test']['top5'])}}}",
        f"\\newcommand{{\\cnNoPreEce}}{{{100.0 * c21['test']['ece']:.1f}}}",
        f"\\newcommand{{\\cnTest}}{{{pct(dep['test']['top1'])}}}",
        f"\\newcommand{{\\cnVal}}{{{pct(dep['best_val_acc'])}}}",
        f"\\newcommand{{\\cnTopFive}}{{{pct(dep['test']['top5'])}}}",
        f"\\newcommand{{\\cnEce}}{{{100.0 * dep['test']['ece']:.1f}}}",
        f"\\newcommand{{\\cnTrainN}}{{{sc['cn241_21/train']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnTestN}}{{{sc['cn241_21/test']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnValN}}{{{sc['cn241_21/val']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnPreValN}}{{{sc['cn241_all/val']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnPrePoolN}}"
        f"{{{sc['cn241_all/train'] + sc['cn241_all/val']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnAllN}}"
        f"{{{sc['cn241_all/train'] + sc['cn241_all/val'] + sc['cn241_all/test']:,}}}".replace(",", "{,}"),
        f"\\newcommand{{\\cnEpochs}}{{{len(dep['history'])}}}",
        f"\\newcommand{{\\cnFuseTop}}{{{pct(fus['top1'])}}}",
        f"\\newcommand{{\\cnFuseTopFive}}{{{pct(fus['top5'])}}}",
        f"\\newcommand{{\\cnFuseSingle}}{{{pct(fus['top1_single_view'])}}}",
    ]
    gain_pre = 100.0 * (dep["test"]["top1"] - c21["test"]["top1"])
    lines += [
        f"\\newcommand{{\\cnGainPretrain}}{{{gain_pre:+.1f}}}",
        f"\\newcommand{{\\cnFuseGain}}"
        f"{{{100.0 * (fus['top1'] - fus['top1_single_view']):+.1f}}}",
    ]
    # accuracy restricted to the twenty dish rows of the 21x21 matrix
    import numpy as _np

    cm = _np.array(fus["confusion"], dtype=float)
    names = fus["classes"]
    other = names.index("other_cn")
    keep = [i for i in range(len(names)) if i != other]
    dish_acc = cm[_np.ix_(keep, keep)].trace() / cm[keep].sum()
    lines += [
        f"\\newcommand{{\\cnDishAcc}}{{{100.0 * dish_acc:.1f}}}",
        f"\\newcommand{{\\cnOtherRecall}}{{{100.0 * cm[other, other] / cm[other].sum():.1f}}}",
        f"\\newcommand{{\\cnDishN}}{{{int(cm[keep].sum()):,}}}".replace(",", "{,}"),
    ]
    tp = _np.diag(cm)
    prec = tp / cm.sum(0)
    rec = tp / cm.sum(1)
    macro_f1 = (2 * prec * rec / (prec + rec)).mean()
    lines.append(f"\\newcommand{{\\cnMacroFone}}{{{100.0 * macro_f1:.1f}}}")

    gate = tj("domain_gate_pre.json")
    for key, macro in (
        ("val", "Val"), ("in", "In"), ("out_cn", "OutCn"),
        ("out_ood", "OutOod"), ("out_other", "OutOther"), ("real", "Real"),
    ):
        s = gate["sets"][key]
        lines += [
            f"\\newcommand{{\\gate{macro}}}{{{pct(s['accept_domain_on'])}}}",
            f"\\newcommand{{\\gate{macro}Off}}{{{pct(s['accept_domain_off'])}}}",
        ]
    lines += [
        f"\\newcommand{{\\gateThr}}{{{gate['domain_threshold']:.4f}}}",
        f"\\newcommand{{\\gateInTop}}{{{pct(gate['in_top1_21class'])}}}",
        f"\\newcommand{{\\gateInCost}}"
        f"{{{100.0 * (gate['sets']['in']['accept_domain_off'] - gate['sets']['in']['accept_domain_on']):.1f}}}",
        f"\\newcommand{{\\gateValCost}}"
        f"{{{100.0 * (gate['sets']['val']['accept_domain_off'] - gate['sets']['val']['accept_domain_on']):.1f}}}",
        f"\\newcommand{{\\gateOutCnGain}}"
        f"{{{100.0 * (gate['sets']['out_cn']['accept_domain_off'] - gate['sets']['out_cn']['accept_domain_on']):.1f}}}",
    ]

    web = tj("cn_web20.json")
    ext = tj("cn_external.json")
    lines += [
        f"\\newcommand{{\\webN}}{{{web['all']['n']}}}",
        f"\\newcommand{{\\webTop}}{{{pct(web['all']['top1'])}}}",
        f"\\newcommand{{\\webAccept}}{{{pct(web['all']['accept_rate'])}}}",
        f"\\newcommand{{\\webTopAcc}}{{{pct(web['all']['top1_accepted'])}}}",
        f"\\newcommand{{\\extN}}{{{ext['all']['n']}}}",
        f"\\newcommand{{\\extTop}}{{{pct(ext['all']['top1'])}}}",
        f"\\newcommand{{\\extAccept}}{{{pct(ext['all']['accept_rate'])}}}",
    ]

    abl = {}
    for name, macro in (("cn241_21_strong", "Strong"), ("cn241_21_bal", "Bal"),
                        ("cn241_21_focal", "Focal"), ("cn241_21_bal_noother", "BalNoOther")):
        abl[macro] = tj(name + ".json")
        lines += [
            f"\\newcommand{{\\abl{macro}Test}}{{{pct(abl[macro]['test']['top1'])}}}",
            f"\\newcommand{{\\abl{macro}Val}}{{{pct(abl[macro]['best_val_acc'])}}}",
            f"\\newcommand{{\\abl{macro}TopFive}}{{{pct(abl[macro]['test']['top5'])}}}",
            f"\\newcommand{{\\abl{macro}Ece}}{{{100.0 * abl[macro]['test']['ece']:.1f}}}",
        ]
    route = tj("tab_route.json")["verdict_time"]
    lines += [
        f"\\newcommand{{\\routeCn}}{{{route['cn']['mean_ms']:.0f}}}",
        f"\\newcommand{{\\routeSingle}}{{{route['single']['mean_ms']:.0f}}}",
    ]

    PAPER.mkdir(parents=True, exist_ok=True)
    (PAPER / "numbers.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()